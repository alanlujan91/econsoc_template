// Builds proof-kinds.mjs: src/proof-kinds.mjs plus myst-to-tex 1.0.48 with the kindToEnvironment
// hunk of jupyter-book/mystmd PR 3031 applied. Once a mystmd release ships that PR, delete the
// plugin, this script and package.json; the four kinds then export natively.
//
// Only the kindToEnvironment hunk is applied. The PR's other hunk adds \newtheorem lines to
// TexProofSerializer's preamble, which the plugin never emits: its inner render's preamble is
// discarded, and template.tex defines the four environments.

import { readFile } from 'node:fs/promises';
import { build } from 'esbuild';

const BASE = '1.0.48';
const ANCHOR = "        case 'corollary':\n            return 'corollary';\n";
const ADDED = ['algorithm', 'assumption', 'criterion', 'property']
  .map((kind) => `        case '${kind}':\n            return '${kind}';\n`)
  .join('');

const { version } = JSON.parse(
  await readFile(new URL('./node_modules/myst-to-tex/package.json', import.meta.url), 'utf8'),
);
if (version !== BASE) throw new Error(`myst-to-tex ${version} installed, the patch targets ${BASE}`);

const pr3031 = {
  name: 'mystmd-pr-3031',
  setup(b) {
    b.onLoad({ filter: /myst-to-tex[\\/]dist[\\/]proof\.js$/ }, async ({ path }) => {
      const source = await readFile(path, 'utf8');
      // Exactly one anchor, or the patch would land in the wrong place or nowhere.
      if (source.split(ANCHOR).length !== 2) throw new Error(`PR 3031 anchor not found once in ${path}`);
      return { contents: source.replace(ANCHOR, ANCHOR + ADDED), loader: 'js' };
    });
  },
};

// `node build.mjs --check` builds in memory and fails if the committed bundle differs from it.
const check = process.argv.includes('--check');
const outfile = new URL('./proof-kinds.mjs', import.meta.url).pathname;

const result = await build({
  entryPoints: [new URL('./src/proof-kinds.mjs', import.meta.url).pathname],
  outfile,
  write: !check,
  // The bundle names each CommonJS module by its path from here, so fix it for any cwd
  absWorkingDir: new URL('.', import.meta.url).pathname,
  bundle: true,
  format: 'esm',
  platform: 'node',
  // Dropping whitespace drops the dependencies' comments, which carry Unicode dashes and quotes;
  // identifiers stay readable.
  minifyWhitespace: true,
  charset: 'ascii',
  legalComments: 'none',
  banner: {
    js: `// Generated by plugins/build.mjs from plugins/src/proof-kinds.mjs and myst-to-tex ${BASE} with jupyter-book/mystmd PR 3031 applied. Do not edit.`,
  },
  plugins: [pr3031],
  logLevel: check ? 'warning' : 'info',
});

if (check) {
  const committed = await readFile(outfile, 'utf8').catch(() => '');
  if (result.outputFiles[0].text !== committed) {
    console.error('plugins/proof-kinds.mjs is stale: run `npm run build` in plugins/');
    process.exit(1);
  }
  console.log('plugins/proof-kinds.mjs matches a fresh build');
}
