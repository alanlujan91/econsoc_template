// Builds econsoc.mjs, the one plugin a paper lists: src/index.mjs and its repairs, with the
// exact versions package.json pins of myst-to-tex (the release mystmd ships, which renders the
// blocks the repairs write whole) and its dependencies.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = (file) => fileURLToPath(new URL(file, import.meta.url));
const readJson = async (file) => JSON.parse(await readFile(here(file), 'utf8'));

const pkg = await readJson('./package.json');
const BASE = pkg.dependencies['myst-to-tex'];
const { version } = await readJson('./node_modules/myst-to-tex/package.json');
if (version !== BASE) throw new Error(`myst-to-tex ${version} installed, package.json pins ${BASE}: run npm ci`);

// `node build.mjs --check` builds in memory and fails if the committed bundle differs from it.
// `--entry FILE --outfile FILE` bundles another entry point, for trying a repair in isolation.
const check = process.argv.includes('--check');
const arg = (flag) => (process.argv.includes(flag) ? process.argv[process.argv.indexOf(flag) + 1] : undefined);
const outfile = arg('--outfile') ?? here('./econsoc.mjs');

const result = await build({
  entryPoints: [arg('--entry') ?? here('./src/index.mjs')],
  outfile,
  write: false,
  // The bundle names each CommonJS module by its path from here, so fix it for any cwd
  absWorkingDir: here('.'),
  bundle: true,
  format: 'esm',
  platform: 'node',
  // Dropping whitespace drops the dependencies' comments, which carry Unicode dashes and quotes;
  // identifiers stay readable.
  minifyWhitespace: true,
  charset: 'ascii',
  legalComments: 'none',
  banner: {
    js: `// Generated by plugins/build.mjs from plugins/src/ with myst-to-tex ${BASE} (mystmd ${pkg.econsoc.mystmd}). Do not edit.`,
  },
  logLevel: check ? 'warning' : 'info',
});

// esbuild leaves a regex literal's characters as they are (myst-common's normalizeLabel holds
// curly quotes), so every non-ASCII UTF-16 unit is escaped here, the same in a string or a regex
const ascii = (text) => text.replace(/[^\0-\x7e]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`);
const text = ascii(result.outputFiles[0].text);

if (check) {
  const committed = await readFile(outfile, 'utf8').catch(() => '');
  if (text !== committed) {
    console.error('plugins/econsoc.mjs is stale: run `npm run build` in plugins/');
    process.exit(1);
  }
  console.log('plugins/econsoc.mjs matches a fresh build');
} else {
  await writeFile(outfile, text);
  console.log(`wrote ${outfile} (${Math.round(text.length / 1024)} kB)`);
}
